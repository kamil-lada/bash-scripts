#!/bin/bash
# Generate a Caddy Docker Compose stack — asks questions, writes files, starts nothing.
#
# Modes:
#   inner       plain HTTP behind the edge Caddy (TLS at the edge), stock image,
#               published on <docker host IP>:8090 only, edge trusted as proxy
#   standalone  Caddy terminates TLS itself: Cloudflare DNS-01 build, ports 80/443
#
# Generated in the stack directory (default /opt/stacks/caddy):
#   compose.yaml
#   Dockerfile.<mode>     copy of apps/caddy/docker/Dockerfile.<mode>
#   .env                  compose settings — plain KEY=value
#   caddy.env             CF_API_TOKEN (standalone only, 0640)
#   conf/Caddyfile        starter config, only when missing (never overwritten);
#                         conf/ is mounted as a directory -> /etc/caddy (read-only)
#   data/ config/ logs/   Caddy storage
# Re-running regenerates everything except conf/Caddyfile and data.
#
# Then, in the stack directory:
#   install  docker compose up -d --build
#   update   docker compose build --pull --no-cache && docker compose up -d
#   apply    docker compose restart caddy
#            (no interruption: docker compose exec caddy caddy reload --config /etc/caddy/Caddyfile)
#
# Usage: docker-setup_caddy.sh
set -eEuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../../../lib/common.sh"

trap 'echo -e "${RED}Script failed${NC}" >&2' ERR

readonly CF_PLUGIN=github.com/caddy-dns/cloudflare
readonly MANAGED_MARK="# Generated by docker-setup_caddy.sh — re-run the script to change it"

MODE="inner"
STACK_DIR=""
CF_ZONE=""
CF_API_TOKEN=""
EXTRA_PLUGINS=""
PLUGINS=""
CADDY_VERSION="2"
CADDY_IMAGE="local/caddy"
NETWORKS=""
TZ_NAME=""
BIND_IP=""
INNER_PORT="8090"
TRUSTED_PROXIES=""
CATCH_ALL_UPSTREAM=""
INSTALL_STARTER="n"
EXISTING="n"
HAVE_DOCKER="n"

############################################################# HELPERS
# ask_optional "Question" CURRENT -> answer; "-" clears the current value
ask_optional() {
    local answer
    answer=$(ask "$1 (- for none)" "$2")
    [[ "$answer" == "-" ]] && answer=""
    echo "$answer"
}

validate_stack_dir() {
    [[ "$1" == /* && "$1" != "/" && ! "$1" =~ [[:space:]] ]] || return 1
    case "$1" in
        /etc*|/usr*|/boot*|/proc*|/sys*|/dev*|/run*|/var/lib/docker*) return 1 ;;
    esac
}

# The directory, or its nearest existing parent, must be writable by this user
stack_dir_writable() {
    local probe="$1"
    while [[ ! -e "$probe" ]]; do probe="$(dirname "$probe")"; done
    [[ -d "$probe" && -w "$probe" ]]
}

validate_networks() {
    local n
    for n in $1; do
        [[ "$n" =~ ^[A-Za-z0-9][A-Za-z0-9_.-]*$ ]] || return 1
    done
}

validate_mode() {
    [[ "$1" == "inner" || "$1" == "standalone" ]]
}

dc() { docker compose --project-directory "$STACK_DIR" -f "$STACK_DIR/compose.yaml" "$@"; }

load_existing() {
    local env="$STACK_DIR/.env" p extra=""
    [[ -f "$env" ]] || return 0
    EXISTING="y"
    MODE=$(conf_get "$env" CADDY_MODE)
    validate_mode "$MODE" || MODE="inner"
    CF_ZONE=$(conf_get "$env" CF_ZONE)
    CADDY_VERSION=$(conf_get "$env" CADDY_VERSION)
    CADDY_IMAGE=$(conf_get "$env" CADDY_IMAGE)
    NETWORKS=$(conf_get "$env" CADDY_NETWORKS)
    TZ_NAME=$(conf_get "$env" TZ)
    BIND_IP=$(conf_get "$env" CADDY_BIND_IP)
    INNER_PORT=$(conf_get "$env" CADDY_PORT)
    PLUGINS=$(conf_get "$env" CADDY_PLUGINS)
    validate_caddy_plugins "$PLUGINS" || { log_error "Invalid CADDY_PLUGINS in $env"; exit 1; }
    for p in $PLUGINS; do
        [[ "$p" == "$CF_PLUGIN" ]] || extra+="${extra:+ }$p"
    done
    EXTRA_PLUGINS="$extra"
    : "${CADDY_VERSION:=2}" "${CADDY_IMAGE:=local/caddy}" "${INNER_PORT:=8090}"
}

# Address of the interface that has the default route (sensible bind default)
default_ip() {
    ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p' | head -n1
}

############################################################# QUESTIONS
gather_config() {
    log_section "Caddy Docker stack — configuration"

    if command -v docker &>/dev/null && docker info &>/dev/null; then
        HAVE_DOCKER="y"
    else
        log_warning "Docker not reachable — files are generated, but compose.yaml is not checked"
    fi

    local default_dir=/opt/stacks/caddy
    while true; do
        STACK_DIR=$(ask "Stack directory" "$default_dir")
        STACK_DIR="${STACK_DIR%/}"
        if ! validate_stack_dir "$STACK_DIR"; then
            log_error "Use an absolute path without spaces, outside system directories"
            continue
        fi
        stack_dir_writable "$STACK_DIR" && break
        log_error "$(id -un) cannot write $STACK_DIR. Create it for this user (files then belong to"
        log_error "the user who runs docker compose), then answer again:"
        log_error "  sudo mkdir -p $STACK_DIR && sudo chown $(id -un): $STACK_DIR"
    done
    load_existing
    if [[ "$EXISTING" == "y" ]]; then
        log_warning "Existing stack — compose.yaml, Dockerfile and .env are regenerated, conf/Caddyfile and data/ are kept"
        confirm "Continue?" y || exit 0
    fi

    log_info "inner = plain HTTP behind the edge Caddy; standalone = own TLS via Cloudflare DNS-01"
    while true; do
        MODE=$(ask "Mode (inner/standalone)" "$MODE")
        validate_mode "$MODE" && break
        log_error "Answer inner or standalone"
    done

    while true; do
        CF_ZONE=$(ask "Domain of the host names (e.g. example.com)" "$CF_ZONE")
        CF_ZONE="${CF_ZONE,,}"
        validate_domain "$CF_ZONE" && [[ "$CF_ZONE" == *.* ]] && break
        log_error "Invalid domain: '$CF_ZONE'"
    done

    if [[ "$MODE" == "standalone" ]]; then
        ask_cf_token CF_API_TOKEN "$CF_ZONE" "$(conf_get "$STACK_DIR/caddy.env" CF_API_TOKEN)"
        while true; do
            EXTRA_PLUGINS=$(ask_optional "Additional Caddy plugins (Go package paths, space separated)" "$EXTRA_PLUGINS")
            validate_caddy_plugins "$EXTRA_PLUGINS" && break
            log_error "Use Go package paths like github.com/mholt/caddy-ratelimit"
        done
        PLUGINS="$CF_PLUGIN${EXTRA_PLUGINS:+ $EXTRA_PLUGINS}"
    else
        PLUGINS=""
        log_info "Publish the port on one address only (the docker host's SERVER address), not 0.0.0.0"
        while true; do
            BIND_IP=$(ask "Address to publish on" "${BIND_IP:-$(default_ip)}")
            validate_ip "$BIND_IP" && break
            log_error "Use an IPv4 address of this host"
        done
        while true; do
            INNER_PORT=$(ask "Port" "$INNER_PORT")
            validate_port "$INNER_PORT" && break
            log_error "Invalid port"
        done
    fi

    while true; do
        CADDY_VERSION=$(ask "Caddy image tag (2 = latest 2.x, or e.g. 2.11)" "$CADDY_VERSION")
        [[ "$CADDY_VERSION" =~ ^2(\.[0-9]+){0,2}$ ]] && break
        log_error "Use 2, 2.x or 2.x.y"
    done

    log_info "Docker networks to join: Caddy reaches containers by name only on shared networks."
    if [[ "$HAVE_DOCKER" == "y" ]]; then
        # Only standalone networks (docker network create): compose-owned ones carry the
        # com.docker.compose.network label and are recreated with their project
        local ext
        ext=$(docker network ls -q | xargs -r docker network inspect \
                --format '{{.Name}} {{index .Labels "com.docker.compose.network"}}' 2>/dev/null \
            | awk 'NF == 1 && $1 !~ /^(bridge|host|none)$/ {print $1}' | sort | tr '\n' ' ')
        log_info "Existing external networks: ${ext:-none}"
    fi
    while true; do
        NETWORKS=$(ask_optional "Networks (space separated, external)" "$NETWORKS")
        validate_networks "$NETWORKS" && break
        log_error "Invalid network name"
    done
    if [[ "$MODE" == "inner" && -z "$NETWORKS" ]]; then
        log_warning "Inner Caddy without networks can reach containers only by published ports"
    fi

    local tz_default
    tz_default=$(timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || echo UTC)
    while true; do
        TZ_NAME=$(ask "Timezone" "${TZ_NAME:-$tz_default}")
        validate_timezone "$TZ_NAME" && break
        log_error "Unknown timezone: '$TZ_NAME'"
    done

    if [[ ! -s "$STACK_DIR/conf/Caddyfile" ]]; then
        INSTALL_STARTER="y"
        if [[ "$MODE" == "inner" ]]; then
            while true; do
                TRUSTED_PROXIES=$(ask "Edge Caddy IP(s) to trust (X-Forwarded-For/-Proto)" "")
                validate_ip_cidr_list "$TRUSTED_PROXIES" && break
                log_error "Use IPv4 addresses or CIDRs separated by spaces"
            done
        else
            while true; do
                TRUSTED_PROXIES=$(ask_optional "Front proxy IPs/CIDRs to trust" "")
                [[ -z "$TRUSTED_PROXIES" ]] || validate_ip_cidr_list "$TRUSTED_PROXIES" && break
                log_error "Use IPv4 addresses or CIDRs separated by spaces"
            done
            while true; do
                CATCH_ALL_UPSTREAM=$(ask_optional "Catch-all target Caddy (IP or host[:port])" "")
                [[ -z "$CATCH_ALL_UPSTREAM" ]] || validate_hostport "$CATCH_ALL_UPSTREAM" && break
                log_error "Use an IP or hostname, optionally with :port"
            done
        fi
    fi

    log_section "Summary"
    printf "  %-24s %s\n" "Stack directory:" "$STACK_DIR"
    printf "  %-24s %s\n" "Mode:" "$MODE"
    printf "  %-24s %s\n" "Domain:" "$CF_ZONE"
    printf "  %-24s %s\n" "Image:" "$CADDY_IMAGE:latest from caddy:$CADDY_VERSION (Dockerfile.$MODE)"
    if [[ "$MODE" == "standalone" ]]; then
        printf "  %-24s %s\n" "Plugins:" "$PLUGINS"
        printf "  %-24s %s\n" "Ports:" "80, 443/tcp, 443/udp"
    else
        printf "  %-24s %s\n" "Published:" "$BIND_IP:$INNER_PORT (plain HTTP)"
    fi
    printf "  %-24s %s\n" "Networks:" "${NETWORKS:-none}"
    printf "  %-24s %s\n" "Timezone:" "$TZ_NAME"
    printf "  %-24s %s\n" "Caddyfile:" "$([[ "$INSTALL_STARTER" == "y" ]] && echo "write starter" || echo "keep existing")"
    [[ -n "$TRUSTED_PROXIES" ]] && printf "  %-24s %s\n" "Trusted proxies:" "$TRUSTED_PROXIES"
    echo ""
    confirm "Write the files?" y || { log_info "Aborted."; exit 0; }
}

############################################################# WRITE
write_compose() {
    local n net_service="" net_top="" ports env_file="" cap=""
    if [[ -n "$NETWORKS" ]]; then
        net_service="    networks:"$'\n'
        net_top=$'\n'"networks:"$'\n'
        for n in $NETWORKS; do
            net_service+="      - $n"$'\n'
            net_top+="  $n:"$'\n'"    external: true"$'\n'
        done
    fi
    if [[ "$MODE" == "standalone" ]]; then
        ports='      - "80:80"
      - "443:443"
      - "443:443/udp"'
        env_file="    env_file: caddy.env"$'\n'
        # HTTP/3: lets quic-go raise its UDP buffer sizes
        cap="    cap_add:"$'\n'"      - NET_ADMIN"$'\n'
    else
        # Only the edge should talk to this port: one address, never 0.0.0.0
        ports='      - "${CADDY_BIND_IP}:${CADDY_PORT}:8090"'
    fi

    cat > "$STACK_DIR/compose.yaml" <<EOF
$MANAGED_MARK
# install: docker compose up -d --build
# update:  docker compose build --pull --no-cache && docker compose up -d
# apply:   docker compose restart caddy
services:
  caddy:
    build:
      context: .
      dockerfile: Dockerfile.$MODE
      args:
        CADDY_VERSION: \${CADDY_VERSION:-2}
        CADDY_PLUGINS: \${CADDY_PLUGINS:-}
    image: \${CADDY_IMAGE}:latest
    container_name: caddy
    restart: unless-stopped
${env_file}    environment:
      TZ: \${TZ:-UTC}
${cap}    ports:
$ports
    volumes:
      # Directory mount: a replaced Caddyfile is seen inside the container
      # (a single-file bind mount keeps showing the old inode)
      - ./conf:/etc/caddy:ro
      - ./data:/data
      - ./config:/config
      - ./logs:/var/log/caddy
    healthcheck:
      # Admin API on localhost:2019 inside the container (also used by caddy reload)
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:2019/config/"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 20s
      start_interval: 2s
${net_service}${net_top}
EOF
}

write_stack() {
    log_section "Writing $STACK_DIR"
    mkdir -p "$STACK_DIR/conf" "$STACK_DIR/data" "$STACK_DIR/config" "$STACK_DIR/logs"

    install -m 0644 "$SCRIPT_DIR/Dockerfile.$MODE" "$STACK_DIR/Dockerfile.$MODE"
    # A mode switch leaves the other Dockerfile unused
    rm -f "$STACK_DIR/Dockerfile.$([[ "$MODE" == "inner" ]] && echo standalone || echo inner)" "$STACK_DIR/Dockerfile"

    {
        echo "$MANAGED_MARK"
        echo "# Plain KEY=value (read by docker compose and by this script on re-run)"
        echo "COMPOSE_PROJECT_NAME=caddy"
        echo "CADDY_MODE=$MODE"
        echo "CADDY_IMAGE=$CADDY_IMAGE"
        echo "CADDY_VERSION=$CADDY_VERSION"
        echo "CADDY_PLUGINS=$PLUGINS"
        echo "CADDY_NETWORKS=$NETWORKS"
        echo "CADDY_BIND_IP=$BIND_IP"
        echo "CADDY_PORT=$INNER_PORT"
        echo "CF_ZONE=$CF_ZONE"
        echo "TZ=$TZ_NAME"
    } > "$STACK_DIR/.env"

    if [[ "$MODE" == "standalone" ]]; then
        ( umask 027; printf '%s\nCF_API_TOKEN=%s\n' "$MANAGED_MARK" "$CF_API_TOKEN" > "$STACK_DIR/caddy.env" )
        chmod 0640 "$STACK_DIR/caddy.env"
    elif [[ -f "$STACK_DIR/caddy.env" ]]; then
        rm -f "$STACK_DIR/caddy.env"
        log_info "Removed caddy.env (inner mode needs no token)"
    fi

    write_compose

    if [[ "$INSTALL_STARTER" == "y" ]]; then
        if [[ "$MODE" == "inner" ]]; then
            caddy_render_template "$SCRIPT_DIR/caddy-Caddyfile.inner.example" "$STACK_DIR/conf/Caddyfile" \
                "$CF_ZONE" "" "$TRUSTED_PROXIES"
        else
            caddy_render_template "$SCRIPT_DIR/../caddy-Caddyfile.example" "$STACK_DIR/conf/Caddyfile" \
                "$CF_ZONE" "$CATCH_ALL_UPSTREAM" "$TRUSTED_PROXIES"
        fi
        log_success "Starter conf/Caddyfile (example hosts — replace with your own)"
    else
        log_info "conf/Caddyfile kept"
    fi

    if [[ "$HAVE_DOCKER" == "y" ]]; then
        local n
        for n in $NETWORKS; do
            docker network inspect "$n" &>/dev/null \
                || log_warning "Network $n does not exist — create it: docker network create $n"
        done
        if dc config --quiet; then
            log_success "compose.yaml is valid"
        else
            log_error "compose.yaml is invalid"
            exit 1
        fi
    fi
}

############################################################# MAIN
main() {
    case "${1:-}" in
        -h|--help) sed -n '2,/^set -eEuo/{/^set/d;s/^# \{0,1\}//p}' "$0"; exit 0 ;;
        "") ;;
        *) log_error "Unknown option: $1 (use --help)"; exit 1 ;;
    esac

    gather_config
    write_stack

    log_section "Done — nothing started"
    echo "  cd $STACK_DIR"
    echo "  docker compose up -d --build                                  # install"
    echo "  docker compose build --pull --no-cache && docker compose up -d   # update"
    echo "  docker compose restart caddy                                  # apply conf/Caddyfile"
    echo "  docker compose run --rm --no-deps caddy caddy validate --config /etc/caddy/Caddyfile   # check first"
    echo ""
    if [[ "$MODE" == "inner" ]]; then
        log_info "Edge: point its fallback to http://$BIND_IP:$INNER_PORT"
        log_info "Limit $BIND_IP:$INNER_PORT to the edge (DOCKER-USER chain or host firewall) — anything on that network can reach it otherwise"
    fi
}

main "$@"
