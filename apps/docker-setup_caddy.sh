#!/bin/bash
# Caddy with Cloudflare DNS-01 certificates as a Docker Compose stack
#
# Docker counterpart of caddy-install_cloudflare.sh (LXC/VM): same Caddyfile
# template (caddy-Caddyfile.example), same deployment model — the Caddyfile is a
# single file managed elsewhere (git / Jenkins) and activated with apply.sh.
# Needs Docker Engine + compose plugin (docker-install_fresh.sh).
#
# Generated stack (default /data/stacks/caddy):
#   compose.yaml, Dockerfile   image built with xcaddy: caddy + caddy-dns/cloudflare (+ extras)
#   .env                       compose settings (image, plugins, TZ, ...) — plain KEY=value
#   caddy.env                  CF_API_TOKEN (0640 root:docker)
#   conf/Caddyfile             the config, mounted as directory -> /etc/caddy (read-only)
#   data/ config/ logs/        certificates, autosave, access logs
#   apply.sh                   validate + activate a Caddyfile    (apps/caddy-docker-apply.sh)
#   update.sh                  rebuild with latest Caddy/plugins  (apps/caddy-docker-update.sh)
#
# Re-running regenerates everything except conf/Caddyfile and data.
#
# Usage: docker-setup_caddy.sh
set -eEuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../lib/common.sh"

LOGFILE="/var/log/docker-setup-caddy.log"

trap 'echo -e "${RED}Script failed. Check $LOGFILE for details${NC}" >&2' ERR

readonly TEMPLATE_SRC="$SCRIPT_DIR/caddy-Caddyfile.example"
readonly APPLY_SRC="$SCRIPT_DIR/caddy-docker-apply.sh"
readonly UPDATE_SRC="$SCRIPT_DIR/caddy-docker-update.sh"
readonly CF_PLUGIN=github.com/caddy-dns/cloudflare
readonly MANAGED_MARK="# Generated by docker-setup_caddy.sh — re-run the script to change it"

STACK_DIR=""
CF_ZONE=""
CF_API_TOKEN=""
EXTRA_PLUGINS=""
PLUGINS=""
CADDY_VERSION="2"
CADDY_IMAGE="local/caddy-cloudflare"
NETWORKS=""
TRUSTED_PROXIES=""
CATCH_ALL_UPSTREAM=""
TZ_NAME=""
INSTALL_STARTER="n"
EXISTING="n"

############################################################# HELPERS
# ask_optional "Question" CURRENT -> answer; "-" clears the current value
ask_optional() {
    local answer
    answer=$(ask "$1 (- for none)" "$2")
    [[ "$answer" == "-" ]] && answer=""
    echo "$answer"
}

validate_stack_dir() {
    [[ "$1" == /* && "$1" != "/" && ! "$1" =~ [[:space:]] ]] || return 1
    case "$1" in
        /etc*|/usr*|/boot*|/proc*|/sys*|/dev*|/run*|/var/lib/docker*) return 1 ;;
    esac
}

validate_networks() {
    local n
    for n in $1; do
        [[ "$n" =~ ^[A-Za-z0-9][A-Za-z0-9_.-]*$ ]] || return 1
    done
}

validate_image_name() {
    [[ "$1" =~ ^[a-z0-9]+([._/-][a-z0-9]+)*$ ]]
}

dc() { docker compose --project-directory "$STACK_DIR" -f "$STACK_DIR/compose.yaml" "$@"; }

load_existing() {
    local env="$STACK_DIR/.env" p extra=""
    [[ -f "$env" ]] || return 0
    EXISTING="y"
    CF_ZONE=$(conf_get "$env" CF_ZONE)
    CADDY_VERSION=$(conf_get "$env" CADDY_VERSION)
    CADDY_IMAGE=$(conf_get "$env" CADDY_IMAGE)
    NETWORKS=$(conf_get "$env" CADDY_NETWORKS)
    TZ_NAME=$(conf_get "$env" TZ)
    PLUGINS=$(conf_get "$env" CADDY_PLUGINS)
    validate_caddy_plugins "$PLUGINS" || { log_error "Invalid CADDY_PLUGINS in $env"; exit 1; }
    for p in $PLUGINS; do
        [[ "$p" == "$CF_PLUGIN" ]] || extra+="${extra:+ }$p"
    done
    EXTRA_PLUGINS="$extra"
    : "${CADDY_VERSION:=2}" "${CADDY_IMAGE:=local/caddy-cloudflare}"
}

############################################################# PRE-FLIGHT
preflight() {
    log_section "Pre-flight checks"
    check_root

    if ! command -v docker &>/dev/null || ! docker info &>/dev/null; then
        log_error "Docker is not installed or not running — run $SCRIPT_DIR/docker-install_fresh.sh first"
        exit 1
    fi
    if ! docker compose version &>/dev/null; then
        log_error "docker compose plugin missing (apt-get install docker-compose-plugin)"
        exit 1
    fi
    log_success "Docker $(docker version --format '{{.Server.Version}}'), compose $(docker compose version --short)"
    getent group docker &>/dev/null || { log_error "Group 'docker' not found"; exit 1; }

    local f
    for f in "$TEMPLATE_SRC" "$APPLY_SRC" "$UPDATE_SRC"; do
        [[ -f "$f" ]] || { log_error "$f not found"; exit 1; }
    done
    check_network_connectivity || exit 1
}

############################################################# INTERACTIVE CONFIG
gather_config() {
    log_section "Configuration"

    local default_dir=/opt/stacks/caddy
    [[ -d /data/stacks ]] && default_dir=/data/stacks/caddy
    while true; do
        STACK_DIR=$(ask "Stack directory" "$default_dir")
        STACK_DIR="${STACK_DIR%/}"
        validate_stack_dir "$STACK_DIR" && break
        log_error "Use an absolute path without spaces, outside system directories"
    done
    load_existing
    if [[ "$EXISTING" == "y" ]]; then
        log_warning "Existing stack found — compose files and tools will be regenerated,"
        log_warning "conf/Caddyfile and certificates (data/) are kept"
        confirm "Continue?" y || exit 0
    fi

    while true; do
        CF_ZONE=$(ask "Cloudflare zone (domain managed in Cloudflare, e.g. example.com)" "$CF_ZONE")
        CF_ZONE="${CF_ZONE,,}"
        validate_domain "$CF_ZONE" && [[ "$CF_ZONE" == *.* ]] && break
        log_error "Invalid domain: '$CF_ZONE'"
    done

    ask_cf_token CF_API_TOKEN "$CF_ZONE" "$(conf_get "$STACK_DIR/caddy.env" CF_API_TOKEN)"

    while true; do
        EXTRA_PLUGINS=$(ask_optional "Additional Caddy plugins (Go package paths, space separated)" "$EXTRA_PLUGINS")
        validate_caddy_plugins "$EXTRA_PLUGINS" && break
        log_error "Use Go package paths like github.com/mholt/caddy-ratelimit"
    done
    PLUGINS="$CF_PLUGIN${EXTRA_PLUGINS:+ $EXTRA_PLUGINS}"

    while true; do
        CADDY_VERSION=$(ask "Caddy image tag to build from (2 = latest 2.x, or e.g. 2.11)" "$CADDY_VERSION")
        [[ "$CADDY_VERSION" =~ ^2(\.[0-9]+){0,2}$ ]] && break
        log_error "Use 2, 2.x or 2.x.y"
    done

    log_info "Join existing Docker networks to proxy containers by name (e.g. reverse_proxy portainer:9000)."
    log_info "Without networks Caddy uses its own default network and reaches upstreams by IP."
    while true; do
        NETWORKS=$(ask_optional "Docker networks (space separated)" "$NETWORKS")
        validate_networks "$NETWORKS" && break
        log_error "Invalid network name"
    done

    local tz_default
    tz_default=$(timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || echo UTC)
    while true; do
        TZ_NAME=$(ask "Timezone" "${TZ_NAME:-$tz_default}")
        validate_timezone "$TZ_NAME" && break
        log_error "Unknown timezone: '$TZ_NAME'"
    done

    if [[ ! -s "$STACK_DIR/conf/Caddyfile" ]]; then
        INSTALL_STARTER="y"
        log_info "Starter Caddyfile (same template as the LXC setup):"
        log_info "- behind a front proxy (e.g. the LXC Caddy catch-all forwarding here)? Give its"
        log_info "  IP(s) so logs and upstreams see real client IPs (trusted_proxies)"
        while true; do
            TRUSTED_PROXIES=$(ask_optional "Front proxy IPs/CIDRs" "")
            [[ -z "$TRUSTED_PROXIES" ]] || validate_ip_cidr_list "$TRUSTED_PROXIES" && break
            log_error "Use IPv4 addresses or CIDRs separated by spaces"
        done
        log_info "- forward every other *.$CF_ZONE host to yet another Caddy (catch-all)?"
        while true; do
            CATCH_ALL_UPSTREAM=$(ask_optional "Catch-all target Caddy (IP or host[:port], HTTPS)" "")
            [[ -z "$CATCH_ALL_UPSTREAM" ]] || validate_hostport "$CATCH_ALL_UPSTREAM" && break
            log_error "Use an IP or hostname, optionally with :port"
        done
    fi

    local busy
    busy=$(ss -Hltnup '( sport = :80 or sport = :443 )' 2>/dev/null | grep -v 'docker-proxy' || true)
    if [[ -n "$busy" ]]; then
        log_warning "Ports 80/443 are used by another process on this host:"
        echo "$busy" | sed 's/^/  /'
        confirm "Continue anyway?" n || exit 1
    fi

    log_section "Summary"
    printf "  %-26s %s\n" "Stack directory:" "$STACK_DIR"
    printf "  %-26s %s\n" "Cloudflare zone:" "$CF_ZONE"
    printf "  %-26s %s\n" "Image:" "$CADDY_IMAGE:latest (from caddy:$CADDY_VERSION)"
    printf "  %-26s %s\n" "Plugins:" "$PLUGINS"
    printf "  %-26s %s\n" "Networks:" "${NETWORKS:-default}"
    printf "  %-26s %s\n" "Timezone:" "$TZ_NAME"
    printf "  %-26s %s\n" "Caddyfile:" "$([[ "$INSTALL_STARTER" == "y" ]] && echo "install starter (example hosts in $CF_ZONE)" || echo "keep existing")"
    if [[ "$INSTALL_STARTER" == "y" ]]; then
        printf "  %-26s %s\n" "Trusted front proxies:" "${TRUSTED_PROXIES:-none}"
        printf "  %-26s %s\n" "Catch-all *.$CF_ZONE:" \
            "$([[ -n "$CATCH_ALL_UPSTREAM" ]] && echo "-> https://$CATCH_ALL_UPSTREAM" || echo "none")"
    fi
    echo ""
    confirm "Proceed?" y || { log_info "Aborted."; exit 0; }
}

############################################################# WRITE STACK
ensure_networks() {
    local n
    for n in $NETWORKS; do
        if docker network inspect "$n" &>/dev/null; then
            log_success "Network $n exists"
        elif confirm "Network $n does not exist — create it (bridge)?" y; then
            run_cmd "Creating network $n" docker network create --driver bridge "$n"
        else
            log_error "Network $n is required by compose.yaml"
            exit 1
        fi
    done
}

write_stack() {
    log_section "Writing stack to $STACK_DIR"

    install -d -m 2775 -o root -g docker "$STACK_DIR" "$STACK_DIR/conf"
    install -d -m 0750 -o root -g docker "$STACK_DIR/data" "$STACK_DIR/config"
    install -d -m 0755 "$STACK_DIR/logs"

    cat > "$STACK_DIR/Dockerfile" <<'EOF'
# Generated by docker-setup_caddy.sh — re-run the script to change it
# Caddy + DNS plugins, built with xcaddy (official caddy:*-builder image)
ARG CADDY_VERSION=2
FROM caddy:${CADDY_VERSION}-builder AS builder
ARG CADDY_PLUGINS="github.com/caddy-dns/cloudflare"
RUN set -eu; \
    args=""; \
    for p in $CADDY_PLUGINS; do args="$args --with $p"; done; \
    xcaddy build $args

FROM caddy:${CADDY_VERSION}
COPY --from=builder /usr/bin/caddy /usr/bin/caddy
EOF

    {
        echo "$MANAGED_MARK"
        echo "# Plain KEY=value (read by compose and update.sh, never sourced)"
        echo "COMPOSE_PROJECT_NAME=caddy"
        echo "CADDY_IMAGE=$CADDY_IMAGE"
        echo "CADDY_VERSION=$CADDY_VERSION"
        echo "CADDY_PLUGINS=$PLUGINS"
        echo "CADDY_NETWORKS=$NETWORKS"
        echo "CF_ZONE=$CF_ZONE"
        echo "TZ=$TZ_NAME"
    } > "$STACK_DIR/.env"
    chmod 0664 "$STACK_DIR/.env"

    ( umask 027; printf '%s\nCF_API_TOKEN=%s\n' "$MANAGED_MARK" "$CF_API_TOKEN" > "$STACK_DIR/caddy.env" )
    chown root:docker "$STACK_DIR/caddy.env"
    chmod 0640 "$STACK_DIR/caddy.env"

    local n net_service="" net_top=""
    if [[ -n "$NETWORKS" ]]; then
        net_service="    networks:"$'\n'
        net_top=$'\n'"networks:"$'\n'
        for n in $NETWORKS; do
            net_service+="      - $n"$'\n'
            net_top+="  $n:"$'\n'"    external: true"$'\n'
        done
    fi

    cat > "$STACK_DIR/compose.yaml" <<EOF
$MANAGED_MARK
services:
  caddy:
    build:
      context: .
      args:
        CADDY_VERSION: \${CADDY_VERSION:-2}
        CADDY_PLUGINS: \${CADDY_PLUGINS}
    image: \${CADDY_IMAGE}:latest
    container_name: caddy
    restart: unless-stopped
    env_file: caddy.env
    environment:
      TZ: \${TZ:-UTC}
    # HTTP/3: lets quic-go raise its UDP buffer sizes
    cap_add:
      - NET_ADMIN
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    volumes:
      # Directory mount: apply.sh replaces the file atomically, a single-file
      # bind mount would keep showing the old inode inside the container
      - ./conf:/etc/caddy:ro
      - ./data:/data
      - ./config:/config
      - ./logs:/var/log/caddy
    healthcheck:
      # Admin API on localhost:2019 (needed by apply.sh reloads too)
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:2019/config/"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 20s
      start_interval: 2s
${net_service}${net_top}
EOF
    chmod 0664 "$STACK_DIR/compose.yaml" "$STACK_DIR/Dockerfile"

    install -m 0775 -o root -g docker "$APPLY_SRC" "$STACK_DIR/apply.sh"
    install -m 0775 -o root -g docker "$UPDATE_SRC" "$STACK_DIR/update.sh"

    if [[ "$INSTALL_STARTER" == "y" ]]; then
        caddy_render_template "$TEMPLATE_SRC" "$STACK_DIR/conf/Caddyfile" \
            "$CF_ZONE" "$CATCH_ALL_UPSTREAM" "$TRUSTED_PROXIES"
        log_success "Starter Caddyfile: $STACK_DIR/conf/Caddyfile (example hosts — replace via your deployment)"
    else
        log_info "Existing $STACK_DIR/conf/Caddyfile kept"
    fi
    chown root:docker "$STACK_DIR/conf/Caddyfile"
    chmod 0664 "$STACK_DIR/conf/Caddyfile"

    run_cmd "Checking compose.yaml" dc config --quiet
    log_success "Stack files written"
}

build_and_start() {
    log_section "Building and starting"
    log_info "Building $CADDY_IMAGE:latest with $PLUGINS (first build takes a few minutes)..."
    run_cmd "Building image" dc build --pull caddy

    if ! "$STACK_DIR/apply.sh" --check 2>&1 | tee -a "$LOGFILE"; then
        log_error "Caddyfile validation failed — fix $STACK_DIR/conf/Caddyfile, then: $STACK_DIR/apply.sh"
        exit 1
    fi

    run_cmd "Starting stack" dc up -d --force-recreate --remove-orphans

    local i status=""
    for (( i = 0; i < 30; i++ )); do
        status=$(docker inspect -f '{{.State.Health.Status}}' caddy 2>/dev/null || echo missing)
        [[ "$status" == "healthy" || "$status" == "unhealthy" ]] && break
        sleep 2
    done
    if [[ "$status" != "healthy" ]]; then
        log_error "caddy container is $status"
        dc logs --no-color --tail 30 caddy | sed 's/^/  /' >&2
        exit 1
    fi
    log_success "caddy is healthy ($(docker exec caddy caddy version | awk '{print $1}'))"
    if [[ "$INSTALL_STARTER" == "y" ]]; then
        log_warning "The starter Caddyfile has example hosts — Caddy will try to get certificates for them"
        log_warning "until you deploy your own Caddyfile (watch: docker logs -f caddy)"
    fi
}

############################################################# MAIN
main() {
    case "${1:-}" in
        -h|--help) sed -n '2,/^set -eEuo/{/^set/d;s/^# \{0,1\}//p}' "$0"; exit 0 ;;
        "") ;;
        *) log_error "Unknown option: $1 (use --help)"; exit 1 ;;
    esac

    check_root
    : > "$LOGFILE"

    log_section "Caddy (Cloudflare DNS) Docker stack"
    preflight
    gather_config
    ensure_networks
    write_stack
    build_and_start

    log_section "Done"
    printf "  %-26s %s\n" "Stack:" "$STACK_DIR"
    printf "  %-26s %s\n" "Caddyfile:" "$STACK_DIR/conf/Caddyfile"
    printf "  %-26s %s\n" "Token:" "$STACK_DIR/caddy.env"
    printf "  %-26s %s\n" "Log file:" "$LOGFILE"
    echo ""
    log_info "Deploy a Caddyfile:      $STACK_DIR/apply.sh /path/to/Caddyfile   (in place: apply.sh)"
    log_info "Validate only:           $STACK_DIR/apply.sh --check /path/to/Caddyfile"
    log_info "Update Caddy + plugins:  $STACK_DIR/update.sh   (--check, --rollback, --force)"
    log_info "Deploy users need the docker group (root-equivalent): usermod -aG docker jenkins"
    log_info "No timer is installed — schedule update.sh -q via cron/Jenkins if wanted"
}

main "$@"
